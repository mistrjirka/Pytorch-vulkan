def body(source,name):
    match=re.search(r'private\s+void\s+'+name+r'\s*\(',source)
    start=source.index('{',match.end());level=1;end=start+1
    while level:
        level+=(source[end]=='{')-(source[end]=='}');end+=1
    return source[start+1:end-1]
def translate(text):
    text=text.replace('this.n','int(params.n)').replace('Math.pow(2.0,-52.0)','1.1920928955078125e-7')
    text=re.sub(r'\bdouble\b','float',text);text=re.sub(r'\bboolean\b','bool',text)
    text=text.replace('Math.','').replace(' | ',' || ').replace(' & ',' && ')
    text=re.sub(r'\b([HV])\[([^\]\n]+)\]\[([^\]\n]+)\]',r'\1(\2,\3)',text)
    text=re.sub(r'\b(d|e|ort)\[([^\]\n]+)\]',r'\1(\2)',text)
    return text
